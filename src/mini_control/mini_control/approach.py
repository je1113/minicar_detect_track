# 역할:
# mission_manager가 사용하는 Nav2 접근 기능을 구현한다.
# 이 파일은 별도 실행 노드로 만들지 않는다.

# 작성할 내용:
# 1. Nav2 NavigateToPose 액션 클라이언트를 만든다.
# 2. 자동차 지도 위치와 로봇 위치를 이용해 접근 목표를 계산한다.
#    자동차와 겹치지 않도록 정해진 거리를 두는 목표를 제안한다.
# 3. map 프레임의 목표 위치와 방향을 전송한다.
# 4. 목표 수락 여부와 이동 결과를 처리한다.
# 5. 접근 목표를 취소하는 기능을 만든다.
# 6. 취소 완료 여부를 mission_manager에 전달한다.
# 7. Nav2 연결 실패나 이동 실패를 전달한다.

# 예시 기능:
# send_goal(...)
# cancel_goal(...)
# get_status(...)

# 주의:
# 목표를 계산했다는 것만으로 도달 가능성이 보장되지는 않는다.
# Nav2의 이동 결과를 확인해야 한다.
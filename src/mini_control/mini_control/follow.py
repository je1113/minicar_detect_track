# 역할:
# 자동차의 상대 방향과 거리로 추종 속도를 계산한다.
# 이 파일은 별도 실행 노드로 만들지 않는다.

# 작성할 내용:
# 1. 자동차 중심과 영상 중심의 차이로 회전 속도를 계산한다.
# 2. 거리 정보와 목표 거리의 차이로 전진 속도를 계산한다.
# 3. 최대 전진 속도와 최대 회전 속도를 제한한다.
# 4. 너무 가까우면 전진을 멈춘다.
# 5. 자동차 감지나 거리 정보가 유효하지 않으면 정지를 반환한다.
# 6. 계산한 속도를 mission_manager에 반환한다.

# 예시 기능:
# compute_velocity(...)
# stop_velocity(...)

# 주의:
# 거리 정보의 출처는 카메라 기능을 확인한 뒤 정한다.
# 실제 로봇 cmd_vel 토픽의 메시지 타입에 맞춰 발행해야 한다.
# 자동차 추종과 장애물 회피는 별도 기능이므로,
# 추종 코드만으로 장애물 회피가 구현됐다고 가정하지 않는다.